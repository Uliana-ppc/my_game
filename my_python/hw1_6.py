x = int(input("введите количество дней дней")) #создаем переменную, просящую ввести число, переформатируем строки в числа
y = 7                                          #создаем переменную и помещаем в неё число
print(f"это {x // y} полных недель")           #выводим текст и результат деления без остатка
print(f"осталось {x % y} дней")                #выводим текст и остаток от деления

